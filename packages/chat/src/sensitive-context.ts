const indexedKeywords: readonly AmbiguousKeyword[] = AMBIGUOUS_KEYWORDS.map((entry) => ({
  keywords: entry.keywords.map(toPaddedWords),
  personal: entry.personal.map(toPaddedWords),
  technical: entry.technical.map(toPaddedWords),
}));

// `keyword`, `question` and `contextTerms` are padded with toPaddedWords.
export function keywordHasTechnicalReading(
  keyword: string,
  question: string,
  contextTerms: readonly string[]
): boolean {
  const entry = indexedKeywords.find((candidate) => candidate.keywords.includes(keyword));
  if (entry === undefined) {
    return false;
  }
  if (entry.personal.some((phrase) => containsPhrase(question, phrase))) {
    return false;
  }
  return [...entry.technical, ...contextTerms].some((phrase) => containsPhrase(question, phrase));
}
